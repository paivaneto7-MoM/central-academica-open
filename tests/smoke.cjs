const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
  page.on('dialog', dialog => dialog.accept());
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  try {
    await page.goto('http://127.0.0.1:8000/app.html');
    assert.match((await page.locator('h1').innerText()).replace(/\s+/g, ' ').trim(), /^Bem-vindo de volta, Professor!$/);
    // Regressão visual: a folha de estilos precisa estar carregada no celular.
    await page.locator('link[rel="stylesheet"]').evaluate(async link => {
      const href = link.href;
      const response = await fetch(href, { cache: 'no-store' });
      if (!response.ok) throw new Error('CSS indisponível: ' + response.status);
    });
    assert.equal(await page.locator('.sidebar').evaluate(el => getComputedStyle(el).display), 'none', 'sidebar desktop deve ficar oculta no celular');
    assert.equal(await page.locator('.bottom-nav').evaluate(el => getComputedStyle(el).display), 'flex', 'navegação inferior móvel deve aparecer');
    assert.equal(await page.locator('.quick').evaluate(el => getComputedStyle(el).display), 'grid', 'atalhos devem ser organizados em grade');
    assert.equal(await page.locator('.quick-card').first().evaluate(el => getComputedStyle(el).textDecorationLine), 'none', 'atalhos não devem parecer links sem estilo');
    assert.equal(await page.locator('.hero').evaluate(el => getComputedStyle(el).borderTopLeftRadius), '24px', 'banner deve ter cantos arredondados');
    await assert.equal(await page.locator('#count-disc').textContent(), '0');
    await page.locator('#disc-name').fill('Fundamentos de Enfermagem');
    await page.locator('#disc-term').fill('2027.1');
    await page.locator('#form-disc button[type=submit]').click();
    assert.equal(await page.locator('#count-disc').textContent(), '1');
    await page.locator('#lesson-disc').selectOption({ label: 'Fundamentos de Enfermagem' });
    await page.locator('#lesson-title').fill('Segurança do paciente');
    await page.locator('#lesson-date').fill('2027-03-15');
    await page.locator('#form-lesson button[type=submit]').click();
    assert.equal(await page.locator('#count-lessons').textContent(), '1');
    await page.locator('#task-title').fill('Revisar plano de ensino');
    await page.locator('#form-task button[type=submit]').click();
    assert.equal(await page.locator('#count-tasks').textContent(), '1');
    await page.locator('#task-list button').filter({ hasText: 'Concluir' }).click();
    assert.equal(await page.locator('#count-tasks').textContent(), '0');
    await page.reload();
    assert.equal(await page.locator('#count-disc').textContent(), '1');
    assert.equal(await page.locator('#count-lessons').textContent(), '1');
    assert.equal(await page.locator('#count-tasks').textContent(), '0');
    // Edição preserva os registros existentes e seus vínculos.
    await page.locator('#disc-list button').filter({ hasText: 'Editar' }).click();
    assert.equal(await page.locator('#count-lessons').textContent(), '1');
    await page.locator('#lesson-list button').filter({ hasText: 'Editar' }).click();
    await page.locator('#task-list button').filter({ hasText: 'Editar' }).click();
    await page.locator('#filter-disc').fill('não existe');
    assert.equal(await page.locator('#disc-list .empty').count(), 1);
    await page.locator('#filter-disc').fill('Fundamentos');
    assert.equal(await page.locator('#disc-list .record').count(), 1);
    await page.locator('#filter-lesson').fill('inexistente');
    assert.equal(await page.locator('#lesson-list .empty').count(), 1);
    await page.locator('#filter-lesson').fill('');
    await page.locator('#filter-task').selectOption('pending');
    assert.equal(await page.locator('#task-list .empty').count(), 1);
    await page.locator('#filter-task').selectOption('done');
    assert.equal(await page.locator('#task-list .record').count(), 1);
    await page.locator('#filter-task').selectOption('all');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    assert.match(download.suggestedFilename(), /\.json$/);
    const fs = require('node:fs');
    const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
    assert.equal(exported.disciplines.length, 1);
    assert.equal(exported.lessons.length, 1);
    assert.equal(exported.tasks.length, 1);
    await page.locator('#disc-list button').filter({ hasText: 'Excluir' }).click();
    assert.equal(await page.locator('#count-disc').textContent(), '0');
    assert.equal(await page.locator('#count-lessons').textContent(), '0');
    await page.locator('#clear').click();
    assert.equal(await page.locator('#task-list .empty').count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'mobile horizontal overflow');
    // Novos módulos: agenda, avaliações, atividades e materiais.
    await page.goto('http://127.0.0.1:8000/modulos.html');
    assert.equal(await page.locator('h1').innerText(), 'Minha rotina acadêmica');
    await page.locator('form[data-kind="agenda"] [name="title"]').fill('Reunião pedagógica');
    await page.locator('form[data-kind="agenda"] [name="date"]').fill('2027-04-20');
    await page.locator('form[data-kind="agenda"] button').click();
    assert.equal(await page.locator('#n-agenda').innerText(), '1');
    await page.locator('form[data-kind="avaliacoes"] [name="title"]').fill('Prova P2');
    await page.locator('form[data-kind="avaliacoes"] [name="date"]').fill('2027-04-25');
    await page.locator('form[data-kind="avaliacoes"] button').click();
    assert.equal(await page.locator('#n-avaliacoes').innerText(), '1');
    await page.locator('form[data-kind="atividades"] [name="title"]').fill('Preparar aula');
    await page.locator('form[data-kind="atividades"] button').click();
    assert.equal(await page.locator('#n-atividades').innerText(), '1');
    await page.locator('#list-atividades button').filter({hasText:'Concluir'}).click();
    assert.equal(await page.locator('#n-atividades').innerText(), '0');
    await page.locator('form[data-kind="materiais"] [name="title"]').fill('Bibliografia');
    await page.locator('form[data-kind="materiais"] [name="url"]').fill('https://example.org/');
    await page.locator('form[data-kind="materiais"] button').click();
    assert.equal(await page.locator('#n-materiais').innerText(), '1');
    await page.reload();
    assert.equal(await page.locator('#n-agenda').innerText(), '1');
    assert.equal(await page.locator('#n-materiais').innerText(), '1');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'modules mobile overflow');
    await page.goto('http://127.0.0.1:8000/calendario.html');
    assert.equal(await page.locator('h1').innerText(), 'Calendário acadêmico');
    assert.equal(await page.locator('.weekday').count(), 7);
    assert.ok(await page.locator('.day').count() >= 28);
    await page.locator('[data-view="week"]').click();
    assert.equal(await page.locator('.day').count(), 7);
    await page.locator('[data-view="day"]').click();
    assert.equal(await page.locator('.day').count(), 1);
    await page.locator('[data-ask="materiais"]').click();
    assert.match(await page.locator('#assistant-output').innerText(), /materiais cadastradas/);
    await page.locator('#menu-toggle').click();
    assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'true');
    await page.locator('#menu-close').click();
    assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'false');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'calendar mobile overflow');
    assert.deepEqual(errors, [], 'browser JS errors');
    console.log('PASS: cadastro, aulas, tarefas, persistência, exportação, exclusão em cascata, limpeza e viewport móvel');
  } finally { await browser.close(); }
})().catch(err => { console.error(err); process.exitCode = 1; });
